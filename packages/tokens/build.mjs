// Nova token pipeline: DTCG JSON → CSS variables, Tailwind v4 theme, JS/TS, Figma-ready DTCG.
import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import StyleDictionary from "style-dictionary";

const PREFIX = "nv";
const OUT = "dist/";

// Keep raw OKLCH strings untouched (no color/css transform, which would down-convert to hex).
const TRANSFORMS = [
  "attribute/cti",
  "name/kebab",
  "fontFamily/css",
  "cubicBezier/css",
  "shadow/css/shorthand",
];

const cssVar = (token) => `var(--${token.name})`;
const pathOf = (token) => token.path.join(".");

/** Map a token to its Tailwind v4 theme variable name (or null to skip). */
function tailwindName(token) {
  const [group, a, b] = token.path;
  switch (group) {
    case "palette":
      return b ? `--color-${a}-${b}` : `--color-${a}`;
    case "color":
      return `--color-${a}`;
    case "radius":
      return `--radius-${a}`;
    case "shadow":
      return `--shadow-${a}`;
    case "easing":
      return `--ease-${a}`;
    case "space":
      return a === "base" ? "--spacing" : null;
    case "font":
      if (a === "family") return `--font-${b}`;
      if (a === "weight") return `--font-weight-${b}`;
      if (a === "size") return `--text-${b}`;
      if (a === "line-height") return `--text-${b}--line-height`;
      return null;
    default:
      return null;
  }
}

StyleDictionary.registerFormat({
  name: "nova/tailwind-theme",
  format: ({ dictionary }) => {
    const lines = dictionary.allTokens
      .map((t) => [tailwindName(t), t])
      .filter(([name]) => name)
      .map(([name, t]) => `  ${name}: ${cssVar(t)};`);
    return [
      "/* Generated by @nova/tokens — do not edit. Tailwind v4 theme bound to Nova CSS variables. */",
      "/* Strict mode: Tailwind's default color palette is removed so only Nova colors exist. */",
      "@theme {",
      "  --color-*: initial;",
      "}",
      "",
      "@theme inline {",
      ...lines,
      "}",
      "",
    ].join("\n");
  },
});

/** Resolved DTCG (no references) — importable by Tokens Studio / Figma variables import. */
StyleDictionary.registerFormat({
  name: "nova/dtcg-resolved",
  format: ({ dictionary }) => {
    const root = {};
    for (const t of dictionary.allTokens) {
      let node = root;
      for (const key of t.path.slice(0, -1)) node = node[key] ??= {};
      node[t.path.at(-1)] = {
        $type: t.$type,
        $value: t.$value,
        ...(t.$description ? { $description: t.$description } : {}),
      };
    }
    return `${JSON.stringify(root, null, 2)}\n`;
  },
});

StyleDictionary.registerFormat({
  name: "nova/flat-json",
  format: ({ dictionary }) =>
    `${JSON.stringify(
      Object.fromEntries(dictionary.allTokens.map((t) => [pathOf(t), { name: `--${t.name}`, value: t.$value, type: t.$type, description: t.$description }])),
      null,
      2,
    )}\n`,
});

const isDark = (t) => t.filePath.includes("semantic.dark");

const base = {
  usesDtcg: true,
  log: { verbosity: "silent", warnings: "disabled" },
};

const light = new StyleDictionary({
  ...base,
  source: ["src/primitives.tokens.json", "src/semantic.light.tokens.json"],
  platforms: {
    css: {
      transforms: TRANSFORMS,
      prefix: PREFIX,
      buildPath: OUT,
      files: [
        { destination: "css/light.css", format: "css/variables", options: { selector: ":root", outputReferences: true } },
        { destination: "tailwind/theme.css", format: "nova/tailwind-theme" },
        { destination: "json/light.json", format: "nova/flat-json" },
        { destination: "figma/nova.light.tokens.json", format: "nova/dtcg-resolved" },
      ],
    },
  },
});

const dark = new StyleDictionary({
  ...base,
  source: ["src/primitives.tokens.json", "src/semantic.dark.tokens.json"],
  platforms: {
    css: {
      transforms: TRANSFORMS,
      prefix: PREFIX,
      buildPath: OUT,
      files: [
        {
          destination: "css/dark.css",
          format: "css/variables",
          filter: isDark,
          options: { selector: '.dark, [data-theme="dark"]', outputReferences: true },
        },
        { destination: "json/dark.json", format: "nova/flat-json", filter: isDark },
        { destination: "figma/nova.dark.tokens.json", format: "nova/dtcg-resolved", filter: isDark },
      ],
    },
  },
});

await rm(OUT, { recursive: true, force: true });
await light.buildAllPlatforms();
await dark.buildAllPlatforms();

// tokens.css = light (primitives + semantic) + dark overrides + prefers-color-scheme opt-in.
const [lightCss, darkCss] = await Promise.all([readFile(`${OUT}css/light.css`, "utf8"), readFile(`${OUT}css/dark.css`, "utf8")]);
await writeFile(`${OUT}css/tokens.css`, `${lightCss}\n${darkCss}`);

// JS/TS entry: flat maps for light & dark, plus helpers.
const lightJson = JSON.parse(await readFile(`${OUT}json/light.json`, "utf8"));
const darkJson = JSON.parse(await readFile(`${OUT}json/dark.json`, "utf8"));
await mkdir(`${OUT}js`, { recursive: true });
await writeFile(
  `${OUT}js/index.js`,
  `// Generated by @nova/tokens — do not edit.
export const tokens = ${JSON.stringify(lightJson, null, 2)};
export const darkTokens = ${JSON.stringify(darkJson, null, 2)};
/** Returns the CSS custom property reference for a token path, e.g. cssVar("color.primary") → "var(--nv-color-primary)". */
export function cssVar(path) {
  const t = tokens[path];
  if (!t) throw new Error(\`Unknown Nova token: \${path}\`);
  return \`var(\${t.name})\`;
}
`,
);
const toType = (obj) =>
  `{\n${Object.keys(obj)
    .map((k) => `  ${JSON.stringify(k)}: TokenEntry;`)
    .join("\n")}\n}`;
await writeFile(
  `${OUT}js/index.d.ts`,
  `// Generated by @nova/tokens — do not edit.
export interface TokenEntry { name: string; value: unknown; type: string; description?: string }
export type TokenPath = keyof typeof tokens;
export declare const tokens: ${toType(lightJson)};
export declare const darkTokens: ${toType(darkJson)};
export declare function cssVar(path: TokenPath): string;
`,
);

// Source DTCG (with references) for Tokens Studio / Terrazzo / Figma round-tripping.
await cp("src", `${OUT}dtcg`, { recursive: true });

console.log(`✓ @nova/tokens built: ${Object.keys(lightJson).length} tokens (light) + ${Object.keys(darkJson).length} dark overrides`);
